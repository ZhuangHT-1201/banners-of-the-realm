export function getUnitCost(id, civId) {
  const def = UNIT_DEFS[id];
  const cost = { ...def.cost };
  if (civId === "jin" && id === "cavalry") {
    for (const key of Object.keys(cost)) cost[key] = Math.ceil(cost[key] * CIVS.jin.bonuses.cavalryCost);
  }
  return cost;
}

export function getTechCostByKey(id) {
  return TECH_DEFS[id]?.cost ?? {};
}

export function formatCost(cost) {
  return Object.entries(cost)
    .map(([key, value]) => `${RESOURCE_META[key].short}${value}`)
    .join(" · ");
}
